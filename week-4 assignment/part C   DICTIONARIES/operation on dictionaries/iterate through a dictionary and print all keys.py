students = {
    101: "Ravi",
    102: "Sita",
    103: "Arjun"
}

print("Keys:")
for key in students.keys():
    print(key)

print("Values:")
for value in students.values():
    print(value)

print("Key-Value pairs:")
for key, value in students.items():
    print(key, value)



