def student_info(name, roll_no, branch):
    """Print student details."""
    print("Name:", name)
    print("Roll No:", roll_no)
    print("Branch:", branch)


name = input("Enter student name: ")
roll_no = input("Enter roll number: ")
branch = input("Enter branch: ")

student_info(name, roll_no, branch)




